import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
const require=createRequire(import.meta.url);
const {checkNativeProject,writeNativeProject}=require('../dist/native.cjs');
const pkg=JSON.parse(await readFile('package.json','utf8'));
const root=resolve('.build/bootstrap-native');await mkdir(root,{recursive:true});
const runtime=await readFile('src/native/runtime.c','utf8');
const runtimeModule='export const source = '+JSON.stringify(runtime)+'\n';
await writeFile('bootstrap/runtime-source.arya',runtimeModule);
const filename=resolve('bootstrap/compiler.arya'),one=join(root,'stage1'),two=join(root,'stage2'),three=join(root,'stage3');
const run=(exe,args,options={})=>execFileSync(exe,args,{encoding:'utf8',maxBuffer:32*1024*1024,timeout:180000,...options});
const project=await checkNativeProject(filename,{output:one,outputDirectory:resolve('bootstrap/.arya/bootstrap')});
await writeNativeProject(project,{output:one,outputDirectory:resolve('bootstrap/.arya/bootstrap')});
console.log('Stage 1: TypeScript compiler produced the native Arya-written compiler.');
console.log(run(one,['build',filename,'-o',two]).trim());
console.log('Stage 2: Arya compiled its own source without Node.');
console.log(run(two,['build',filename,'-o',three],{env:{...process.env,PATH:'/usr/bin:/bin:/usr/sbin:/sbin'}}).trim());
const second=await readFile(two+'.c'),third=await readFile(three+'.c');
if(!second.equals(third))throw new Error('Bootstrap did not converge: stage 2/3 generated C differs.');
console.log('Stage 3: generated C is byte-identical to stage 2.');
const sample=resolve('fixtures/native/calculator.arya'),output=join(root,'calculator');
run(three,['build',sample,'-o',output]);
const calculator=run(output,['12','+','8'],{env:{PATH:'/nonexistent'}});
if(calculator!=='20\n')throw new Error('Bootstrapped calculator returned an incorrect result.');
const conformance=resolve('fixtures/native/conformance.arya');
const expected='11 12 720 49995000\n0 1 2\n43 true\n4 512 9\nfallback 0\n2\n3\nTypeError\nReferenceError\ncaught\n';
for(const [label,exe] of [['stage1',one],['stage3',three]]) {
  const sampleOutput=join(root,'conformance-'+label);run(exe,['build',conformance,'-o',sampleOutput]);
  const actual=run(sampleOutput,[],{env:{...process.env,ARYA_GC_STRESS:'1',ARYA_GC_STATS:'1'}});
  if(actual!==expected)throw new Error('Bootstrap conformance failed for '+label+': '+actual);
}
const invalid=join(root,'invalid.arya');await writeFile(invalid,'const value = 1\nvalue = 2\n');
let rejected=false;try{run(three,['check',invalid]);}catch{rejected=true;}if(!rejected)throw new Error('Bootstrapped compiler accepted a const write.');
const installed=resolve('artifacts',`arya-native-${pkg.version}-${process.platform}-${process.arch}`);await mkdir(installed,{recursive:true});
await copyFile(three,join(installed,'arya-native'));
for(const name of ['LICENSE','NOTICE','THIRD-PARTY-NOTICES.txt'])await copyFile(name,join(installed,name));
const evidence={version:pkg.version,platform:process.platform,architecture:process.arch,compilerVersion:run(process.env.ARYA_CC??process.env.CC??'cc',['--version']).split('\n')[0],stages:3,generatedCIdentical:true,generatedCSha256:createHash('sha256').update(third).digest('hex'),binarySha256:createHash('sha256').update(await readFile(three)).digest('hex'),sourceSha256:createHash('sha256').update(await readFile(filename)).digest('hex'),runtimeSha256:createHash('sha256').update(runtime).digest('hex'),calculatorResult:calculator.trim(),conformance:true,constWriteRejected:true};
await writeFile(join(root,'evidence.json'),JSON.stringify(evidence,null,2)+'\n');
await writeFile(join(installed,'BOOTSTRAP.json'),JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify(evidence,null,2));
