import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, writeFile, rm, readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {once} from 'node:events';
import {buildProject, writeProject} from '../src/project.js';
import {chrome} from './helpers/chrome.js';
import {uiCatalog} from '../src/ui-catalog.js';

test('library preview works with keyboard controls, form state, dialogs, clipboard, and motion in Chrome', {skip: !process.env.ARYA_TEST_BROWSER, timeout: 60000}, async t => {
  const root = await mkdtemp(join(tmpdir(), 'arya library browser '));
  let shutdown = async () => {};
  let closeBrowser = async () => {};
  t.after(async () => { try { await closeBrowser(); } finally { try { await shutdown(); } finally { await rm(root, {recursive: true, force: true}); } } });
  const entry = join(root, 'main.arya');
  await writeFile(entry, await readFile('fixtures/examples/ui-library/main.arya', 'utf8'));
  const {start, stop} = await import(pathToFileURL(await writeProject(await buildProject(entry))).href);
  const server = start(0); shutdown = () => stop(server); await once(server, 'listening');
  const page = await chrome(t, 'http://127.0.0.1:' + server.address().port);
  closeBrowser = page.close;
  const {evaluate: js, until, command} = page;
  await page.navigate('/');
  assert.equal(await js('document.querySelector("h1").textContent'), 'Less setup. More possibility.');
  await js('document.querySelector("#buttons-tabs-tab-code").click()');
  assert.equal(await js('document.querySelector("#buttons-tabs-tab-code").getAttribute("aria-selected")'), 'true');
  await js('Object.defineProperty(navigator, "clipboard", {configurable:true, value:{writeText: async value => { window.copiedSource = value; }}}); document.querySelector("#buttons-tabs-panel-code button").click()');
  await until('window.copiedSource?.startsWith("ui.button")');
  assert.equal(await js('window.copiedSource'), await js('document.getElementById("buttons-source").textContent'));
  await js('document.querySelector("#buttons-tabs-tab-code").focus()');
  await command('Input.dispatchKeyEvent', {type: 'keyDown', key: 'ArrowRight', code: 'ArrowRight', windowsVirtualKeyCode: 39});
  assert.equal(await js('document.activeElement.id'), 'buttons-tabs-tab-preview');
  await js('Array.from(document.querySelectorAll("#state button")).find(button=>button.textContent==="Add one").click()');
  assert.equal(await js('document.querySelector("#state [role=status]").textContent'), '1');
  await js('document.querySelector("#state input").click()');
  assert.equal(await js('document.getElementById("conditional-demo").hidden'), false);
  await js('for (const [id, value] of [["demo-name", "Arya"], ["demo-email", "arya@example.com"]]) {const input=document.getElementById(id);input.value=value;input.dispatchEvent(new Event("input", {bubbles:true}));} document.querySelector("#forms button[type=submit]").click()');
  await until('document.getElementById("form-result").textContent === "Preview saved for Arya."');
  assert.equal(await js('document.querySelector("#forms button[type=submit]").disabled'), false);
  await js('const range=document.getElementById("capacity");range.value="35";range.dispatchEvent(new Event("input", {bubbles:true}));');
  assert.equal(await js('document.querySelector("#controls progress").value'), 35);
  await js('document.querySelector("#controls input[type=radio][value=team]").click()');
  assert.equal(await js('document.getElementById("demo-plan").value'), 'team');
  await js('const opener=Array.from(document.querySelectorAll("#navigation button")).find(button=>button.textContent==="Open dialog");opener.focus();opener.click();');
  assert.equal(await js('document.getElementById("welcome-dialog").open'), true);
  assert.equal(await js('document.getElementById("welcome-dialog").contains(document.activeElement)'), true);
  await command('Input.dispatchKeyEvent', {type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9});
  assert.equal(await js('document.getElementById("welcome-dialog").contains(document.activeElement)'), true);
  await command('Input.dispatchKeyEvent', {type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27});
  await until('!document.getElementById("welcome-dialog").open');
  assert.equal(await js('document.activeElement.textContent'), 'Open dialog');
  await js('document.querySelector("[aria-describedby=dialog-hint]").focus()');
  assert.equal(await js('getComputedStyle(document.getElementById("dialog-hint")).visibility'), 'visible');
  await js('document.getElementById("switch-theme").click()');
  await js('document.activeElement?.blur(); for(const button of document.querySelectorAll(".arya-toast button"))button.click(); window.scrollTo(0,0)');
  await js('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
  assert.equal(await js('document.documentElement.dataset.theme'), 'dark');
  await js('document.getElementById("switch-theme").click()');
  if (process.env.ARYA_UI_GALLERY_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_GALLERY_SCREENSHOT);
  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true});
  assert.equal(await js('document.documentElement.scrollWidth <= innerWidth'), true);
  if (process.env.ARYA_UI_MOBILE_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_MOBILE_SCREENSHOT);
  await command('Emulation.setDeviceMetricsOverride', {width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false});
  await page.navigate('/motion');
  await js('document.getElementById("play-loop").click()');
  await until('document.getElementById("orbit").getAnimations().length === 1');
  await js('document.getElementById("pause-loop").click()');
  assert.equal(await js('document.getElementById("orbit").getAnimations()[0].playState'), 'paused');
  await js('document.getElementById("resume-loop").click()');
  assert.equal(await js('document.getElementById("orbit").getAnimations()[0].playState'), 'running');
  await js('document.getElementById("cancel-loop").click()');
  assert.equal(await js('document.getElementById("orbit").getAnimations().length'), 0);
  await js('document.getElementById("play-sequence").click()');
  await until('Array.from(document.querySelectorAll("#stagger-group>div")).some(element=>element.getAnimations().length)');
  await until('document.querySelector("#arya-ui-toasts")?.textContent.includes("Sequence completed.")');
  await js('for(const button of document.querySelectorAll(".arya-toast button"))button.click(); document.getElementById("play-sequence").click()');
  await until('document.getElementById("play-sequence").disabled');
  await js('document.getElementById("stop-sequence").click()');
  await until('!document.getElementById("play-sequence").disabled');
  assert.equal(await js('document.querySelectorAll(".arya-toast").length'), 0);
  await js('document.getElementById("play-parallel").click()');
  await until('document.getElementById("play-parallel").disabled');
  await until('!document.getElementById("play-parallel").disabled');
  await js('document.getElementById("play-custom").click()');
  await until('document.getElementById("custom-motion").getAnimations().length === 1');
  assert.equal(await js('document.getElementById("custom-motion").getAnimations()[0].effect.getKeyframes().length'), 2);
  await until('!document.getElementById("play-custom").disabled');
  await js('document.getElementById("play-loop").click()');
  await command('Emulation.setEmulatedMedia', {features: [{name: 'prefers-reduced-motion', value: 'reduce'}]});
  await js('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
  assert.equal(await js('document.getAnimations().length'), 0);
  await js('document.getElementById("play-loop").click()');
  assert.equal(await js('document.getElementById("orbit").getAnimations().length'), 0);
  if (process.env.ARYA_UI_MOTION_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_MOTION_SCREENSHOT);
  await page.navigate('/guide');
  assert.equal(await js('document.querySelectorAll("#api-reference tbody tr").length'), uiCatalog.length);
  assert.equal(await js('document.querySelectorAll(".kit-guide-step").length'), 10);
  if (process.env.ARYA_UI_GUIDE_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_GUIDE_SCREENSHOT);
  await page.navigate('/');
  await js('document.querySelector("#workspace-mode input[value=team]").click()');
  assert.equal(await js('document.getElementById("demo-plan").value'), 'team');
  await js('const search=document.getElementById("project-search"); search.value="Roadmap"; search.dispatchEvent(new Event("input", {bubbles:true})); search.closest(".arya-search").querySelector("button").click()');
  assert.equal(await js('document.getElementById("project-search").value'), '');
  await command('Emulation.setDeviceMetricsOverride', {width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false});
  await page.navigate('/sections');
  assert.equal(await js('document.querySelectorAll(".kit-demo").length'), 8);
  if (process.env.ARYA_UI_SECTIONS_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_SECTIONS_SCREENSHOT);
  await page.navigate('/templates');
  assert.equal(await js('document.querySelectorAll(".kit-demo").length'), 4);
  if (process.env.ARYA_UI_TEMPLATES_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_TEMPLATES_SCREENSHOT);
  for (const name of ['landing', 'dashboard', 'settings', 'sign-in']) {
    await page.navigate('/templates/' + name);
    assert.equal(await js('document.querySelectorAll("h1").length'), 1);
    if (name === 'landing' && process.env.ARYA_UI_LANDING_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_LANDING_SCREENSHOT);
    if (name === 'dashboard' && process.env.ARYA_UI_DASHBOARD_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_DASHBOARD_SCREENSHOT);
  }
  await js('for (const [id,value] of [["signin-email","arya@example.com"],["signin-password","example-only"]]) {const input=document.getElementById(id);input.value=value;input.dispatchEvent(new Event("input", {bubbles:true}));} document.querySelector("button[type=submit]").click()');
  await until('document.querySelector(".arya-toast")?.textContent.includes("Preview only")');
  assert.equal(await js('location.search'), '');
  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true});
  for (const path of ['/sections', '/templates', '/templates/landing', '/templates/dashboard', '/templates/settings', '/templates/sign-in']) {
    await page.navigate(path);
    assert.equal(await js('document.documentElement.scrollWidth <= innerWidth'), true, path);
  }
  if (process.env.ARYA_UI_TEMPLATE_MOBILE_SCREENSHOT) await page.screenshot(process.env.ARYA_UI_TEMPLATE_MOBILE_SCREENSHOT);
  assert.deepEqual(page.exceptions, []); assert.deepEqual(page.violations, []);
});
